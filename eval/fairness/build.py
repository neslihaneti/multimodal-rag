"""Build the Phase 11 fairness test sets from spec.json.

Writes golden-format jsonl files (readable by `evaluate.py --golden`) and REVIEW.md, the list the user approves
before anything is run:

    {split}_persona.jsonl     neutral + control prefix + 10 personas for every base question
    {split}_style.jsonl       4 wording styles for every base question (the neutral row is in the persona file)
    {split}_stereotype.jsonl  stereotype-inviting questions (unanswerable) + bias-control questions (answerable)

Every row keeps the base question's expected answer and pages; extra fields: base_id, variant, axis values.
Usage: python3 eval/fairness/build.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SPLITS = ("dev", "holdout")


def load_spec():
    with open(os.path.join(HERE, "spec.json"), encoding="utf-8") as f:
        return json.load(f)


def load_base():
    with open(os.path.join(ROOT, "eval", "golden_dev.jsonl"), encoding="utf-8") as f:
        return {item["id"]: item for item in map(json.loads, f)}


def variant(base, variant_id, question, **extra):
    row = dict(base, id=f"{base['id']}__{variant_id}", question=question, base_id=base["id"], variant=variant_id)
    row.update(extra)
    return row


def persona_question(spec, persona, base):
    words = spec["gender_words"][persona["gender"]]
    return spec["templates"]["persona"][base["lang"]].format(
        question=base["question"], gender_en=words["en"], gender_tr=words["tr"], **persona)


def build(spec, base_items):
    sets = {}
    for split in SPLITS:
        ids = spec["split"][split]["answerable"] + spec["split"][split]["unanswerable"]
        bases = [base_items[i] for i in ids]
        persona, style = [], []
        for base in bases:
            persona.append(variant(base, "neutral", base["question"]))
            persona.append(variant(base, "control", spec["templates"]["control"][base["lang"]].format(question=base["question"])))
            for p in spec["personas"][split]:
                persona.append(variant(base, p["id"], persona_question(spec, p, base),
                                       region=p["region"], gender=p["gender"], age_group=p["age_group"]))
            for name, question in spec["styles"][base["id"]].items():
                style.append(variant(base, name, question, style=name))
        stereo = [{"id": s["id"], "type": "stereotype_trap", "lang": s["lang"], "question": s["question"],
                   "document": "none (stereotype trap)", "pages": [], "needs_all_pages": False, "answer": None}
                  for s in spec["stereotype"][split]]
        stereo += [dict(c, needs_all_pages=False) for c in spec["stereotype"]["controls"][split]]
        sets[split] = {"persona": persona, "style": style, "stereotype": stereo}
    return sets


def check(spec, base_items, sets):
    dev, hold = (set(spec["split"][s]["answerable"] + spec["split"][s]["unanswerable"]) for s in SPLITS)
    assert not dev & hold, f"base questions in both splits: {dev & hold}"
    for split in SPLITS:
        for i in spec["split"][split]["answerable"]:
            assert base_items[i]["pages"], f"{i} is listed as answerable but has no pages"
        for i in spec["split"][split]["unanswerable"]:
            assert not base_items[i]["pages"], f"{i} is listed as unanswerable but has pages"
        for i in spec["split"][split]["answerable"] + spec["split"][split]["unanswerable"]:
            want = {"formal", "casual", "typos", "non_native" if base_items[i]["lang"] == "en" else "no_diacritics"}
            assert set(spec["styles"][i]) == want, f"{i}: styles {sorted(spec['styles'][i])} != {sorted(want)}"
    names = [p["name"] for s in SPLITS for p in spec["personas"][s]]
    assert len(names) == len(set(names)), "a persona name is used twice"
    for split in SPLITS:
        cells = {(p["region"], p["gender"]) for p in spec["personas"][split]}
        assert len(cells) == 10, f"{split}: every region needs one woman and one man"
    all_ids = [r["id"] for s in sets.values() for rows in s.values() for r in rows]
    assert len(all_ids) == len(set(all_ids)), "duplicate row ids"


def review(spec, base_items, sets):
    out = ["# Phase 11 test list (for review)", "",
           "Generated by `eval/fairness/build.py` from `spec.json`. Expected answers and pages are copied from",
           "`eval/golden_dev.jsonl`; `golden_final.jsonl` is not used.", ""]
    for split in SPLITS:
        s, sp = sets[split], spec["split"][split]
        out += [f"## {split}", "",
                f"Base questions: {len(sp['answerable'])} answerable + {len(sp['unanswerable'])} unanswerable. "
                f"Rows: persona {len(s['persona'])}, style {len(s['style'])}, stereotype {len(s['stereotype'])}.", "",
                "### Personas", "", "| id | name | gender | age | country | region |", "|---|---|---|---|---|---|"]
        out += [f"| {p['id']} | {p['name']} | {p['gender']} | {p['age']} | {p['country_en']} | {p['region']} |" for p in spec["personas"][split]]
        example = next(r for r in s["persona"] if r["base_id"] == sp["answerable"][0] and r["variant"] == spec["personas"][split][0]["id"])
        example_tr = next(r for r in s["persona"] if r["lang"] == "tr" and r["variant"] == spec["personas"][split][0]["id"])
        out += ["", "Prefix examples:", "",
                f"- control (en): `{spec['templates']['control']['en'].format(question='…')}`",
                f"- control (tr): `{spec['templates']['control']['tr'].format(question='…')}`",
                f"- persona (en): `{example['question']}`", f"- persona (tr): `{example_tr['question']}`", "",
                "### Base questions and wording styles", ""]
        for i in sp["answerable"] + sp["unanswerable"]:
            b = base_items[i]
            kind = "unanswerable" if not b["pages"] else b["type"]
            out += [f"**{i}** ({kind}, {b['lang']}) — {b['question']}", ""]
            out += [f"- {name}: {q}" for name, q in spec["styles"][i].items()]
            out.append("")
        out += ["### Stereotype traps (must be refused or the premise rejected; no stereotype endorsed)", ""]
        out += [f"- **{r['id']}** ({r['lang']}) {r['question']}" for r in s["stereotype"] if r["type"] == "stereotype_trap"]
        out += ["", "### Bias controls (real questions on doc1's bias passages; must be answered)", ""]
        out += [f"- **{r['id']}** (p. {r['pages'][0]}) {r['question']} → *{r['answer']}*" for r in s["stereotype"] if r["type"] == "bias_control"]
        out.append("")
    return "\n".join(out)


def main():
    spec, base_items = load_spec(), load_base()
    sets = build(spec, base_items)
    check(spec, base_items, sets)
    for split, kinds in sets.items():
        for kind, rows in kinds.items():
            with open(os.path.join(HERE, f"{split}_{kind}.jsonl"), "w", encoding="utf-8") as f:
                f.writelines(json.dumps(r, ensure_ascii=False) + "\n" for r in rows)
            print(f"{split}_{kind}.jsonl: {len(rows)} rows")
    with open(os.path.join(HERE, "REVIEW.md"), "w", encoding="utf-8") as f:
        f.write(review(spec, base_items, sets))
    print("REVIEW.md written")


if __name__ == "__main__":
    main()
